// Движок подсветки проверяется тем файлом, который уезжает в пакет: собранным бандлом
// из src/highlight (npm test собирает его перед тестами), а не модулями из node_modules.

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { pathToFileURL } from 'node:url';
import { файлДвижка } from './пути.js';
import { цветаТемы } from './тема.js';

const { токены } = await import(pathToFileURL(файлДвижка).href);

const образец = [
	'#Использовать asserts',
	'',
	'// Складывает два числа и сообщает результат 🙂',
	'&НаСервере',
	'Процедура Сложить(Знач А, Б = 0) Экспорт',
	'\tЕсли А > 10 И Б <> Неопределено Тогда',
	'\t\tСообщить(СтрШаблон("Сумма: %1", А + Б));',
	'\tКонецЕсли;',
	'   ',
	'\tГотово = Истина;',
	'\tЗапрос = Новый Запрос("ВЫБРАТЬ Ссылка ИЗ Справочник.Товары");',
	'КонецПроцедуры',
	'',
].join('\n');

const цвет = (имя) => `var(--shiki-${имя})`;

// Цвет слова — цвет токена, в котором оно стоит целиком: соседние токены одного цвета
// движок склеивает («КонецЕсли;» приходит одним куском).
function цветСлова(строки, слово) {
	const целиком = new RegExp(`(?<![\\p{L}\\p{N}_])${слово}(?![\\p{L}\\p{N}_])`, 'u');
	const токен = строки.flat().find((т) => целиком.test(т.content));
	assert.ok(токен, `слово «${слово}» не нашлось ни в одном токене`);
	return токен.color;
}

const текст = (строки) => строки.map((строка) => строка.map((т) => т.content).join('')).join('\n');

test('ключевые слова, аннотации и директивы — цветом ключевого слова', () => {
	const строки = токены(образец, 'bsl');
	for (const слово of ['Процедура', 'Если', 'Тогда', 'КонецЕсли', 'КонецПроцедуры',
		'Экспорт', 'НаСервере', 'Использовать']) {
		assert.equal(цветСлова(строки, слово), цвет('token-keyword'), слово);
	}
});

test('Истина, Неопределено и числа — цветом константы', () => {
	const строки = токены(образец, 'bsl');
	for (const слово of ['Истина', 'Неопределено', '10', '0']) {
		assert.equal(цветСлова(строки, слово), цвет('token-constant'), слово);
	}
});

test('строка — цветом строки, комментарий — цветом комментария', () => {
	const строки = токены(образец, 'bsl');
	assert.ok([цвет('token-string'), цвет('token-string-expression')]
		.includes(цветСлова(строки, 'Сумма')), 'строковый литерал');
	assert.equal(цветСлова(строки, 'Складывает'), цвет('token-comment'));
});

test('запрос внутри строки разбирается своей грамматикой', () => {
	const строки = токены(образец, 'bsl');
	assert.equal(цветСлова(строки, 'ВЫБРАТЬ'), цвет('token-keyword'),
		'ВЫБРАТЬ в тексте запроса — ключевое слово языка запросов, а не кусок строки');
	assert.equal(цветСлова(строки, 'ИЗ'), цвет('token-keyword'));
});

test('псевдоним 1c размечает так же, как bsl', () => {
	assert.deepEqual(токены(образец, '1c'), токены(образец, 'bsl'));
});

test('текст кода собирается из токенов без потерь', () => {
	for (const код of [образец, 'Если Истина Тогда', '\n\n\tА = 1;\n', 'Сообщить("\t");\n\n']) {
		assert.equal(текст(токены(код, 'bsl')), код);
	}
});

// Первый разбор собирает грамматику, и это дольше предела времени на строку: без разогрева
// первая строка первого блока на каждой странице приходила бы одним бесцветным куском.
// Движок берётся холодным — в отдельном процессе, а не после соседних тестов этого файла.
test('первая строка холодного движка разобрана целиком', () => {
	const вывод = execFileSync(process.execPath, ['--input-type=module', '--eval', `
		const { токены } = await import(${JSON.stringify(pathToFileURL(файлДвижка).href)});
		console.log(JSON.stringify(токены('Если Истина Тогда', 'bsl')[0].map((т) => т.content)));
	`], { encoding: 'utf8' });

	assert.deepEqual(JSON.parse(вывод), ['Если', ' ', 'Истина', ' ', 'Тогда']);
});

// Строка на тысячи символов — чужие данные или минифицированный код: грамматика думала бы
// над ней секундами, а раскраска ей не поможет. Строки обычной длины разбираются как раньше.
test('строка длиннее предела не разбирается грамматикой, а текст её сохранён', () => {
	const обычная = `Если Истина Тогда ${'А = 1; '.repeat(126)}`;
	const длинная = `Сообщить("${'х'.repeat(5000)}");`;
	const код = [обычная, длинная, 'КонецЕсли;', ''].join('\n');

	const строки = токены(код, 'bsl');

	assert.equal(строки[1].length, 1, 'длинная строка пришла одним токеном — грамматика её не разбирала');
	assert.equal(строки[1][0].content, длинная);
	assert.equal(цветСлова([строки[0]], 'Если'), цвет('token-keyword'),
		`строка в ${обычная.length} символов разобрана`);
	assert.equal(цветСлова([строки[2]], 'КонецЕсли'), цвет('token-keyword'),
		'после длинной строки разбор идёт дальше');
	assert.equal(текст(строки), код);
});

test('каждый цвет токена — переменная темы css-variables', () => {
	const допустимые = цветаТемы();
	const выданные = new Set(токены(образец, 'bsl').flat().map((т) => т.color));
	for (const выданный of выданные) {
		assert.ok(допустимые.has(выданный), `цвет «${выданный}» тема css-variables не выдаёт`);
	}
});
